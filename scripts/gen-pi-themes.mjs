// Generates internal/tui/pi_themes_gen.go from Pi's own theme code: every
// colour key of Pi's built-in dark and light themes, resolved to truecolor
// RGB exactly as Pi renders them. Run with the globally installed Pi:
//   COLORTERM=truecolor bun scripts/gen-pi-themes.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { homedir } from 'node:os';

const root = process.env.PI_CODING_AGENT_DIR || `${homedir()}/.bun/install/global/node_modules/@earendil-works/pi-coding-agent`;
const dir = `${root}/dist/modes/interactive/theme/`;
const theme = await import(`${dir}theme.js`);
const version = JSON.parse(readFileSync(`${root}/package.json`, 'utf8')).version;

const out = {};
for (const name of ['dark', 'light']) {
  theme.initTheme(name);
  const keys = Object.keys(JSON.parse(readFileSync(`${dir}${name}.json`, 'utf8')).colors).sort();
  out[name] = {};
  for (const key of keys) {
    const sample = key.endsWith('Bg') ? theme.theme.bg(key, 'x') : theme.theme.fg(key, 'x');
    const m = sample.match(/[34]8;2;(\d+);(\d+);(\d+)/);
    if (!m) throw new Error(`${name}.${key}: not truecolor (set COLORTERM=truecolor)`);
    out[name][key] = m.slice(1).map(Number);
  }
}

let go = `// Code generated by scripts/gen-pi-themes.mjs from Pi ${version}; DO NOT EDIT.

package tui

// piBuiltinThemes holds every colour key of Pi's built-in themes, resolved to
// truecolor RGB by Pi's own theme code.
var piBuiltinThemes = map[string]map[string][3]uint8{
`;
for (const [name, colors] of Object.entries(out)) {
  go += `\t${JSON.stringify(name)}: {\n`;
  for (const [key, [r, g, b]] of Object.entries(colors)) go += `\t\t${JSON.stringify(key)}: {${r}, ${g}, ${b}},\n`;
  go += '\t},\n';
}
go += '}\n';
writeFileSync('internal/tui/pi_themes_gen.go', go);
console.log(`wrote internal/tui/pi_themes_gen.go (Pi ${version}: ${Object.keys(out.dark).length} keys per theme)`);
