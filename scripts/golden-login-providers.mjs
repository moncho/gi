// Pi's built-in providers and their sign-in methods (pi-ai providers/*.js),
// written as internal/inference/login_providers_gen.go for gi's /login.
//   bun scripts/golden-login-providers.mjs [node_modules dir]
import { existsSync, readdirSync, writeFileSync } from "node:fs";
import { homedir } from "node:os";

const candidates = [process.argv[2], `${homedir()}/.bun/install/global/node_modules`, "/workspace/.cache/pi-ref/node_modules"];
const root = candidates.find((dir) => dir && existsSync(`${dir}/@earendil-works/pi-ai/dist/providers/all.js`));
if (!root) throw new Error("pi-ai not found");
const dir = `${root}/@earendil-works/pi-ai/dist/providers`;
const builtin = new Set((await import(`${dir}/all.js`)).getBuiltinProviders());
builtin.add("radius"); // Pi registers Radius beside the model catalogues
const providers = new Map();
for (const file of readdirSync(dir).filter((f) => f.endsWith(".js"))) {
	let mod;
	try { mod = await import(`${dir}/${file}`); } catch { continue; }
	for (const [name, value] of Object.entries(mod)) {
		if (!name.endsWith("Provider")) continue;
		let provider = value;
		try { if (typeof value === "function") provider = value(); } catch { continue; }
		if (!provider?.id || !provider.auth || !builtin.has(provider.id) || providers.has(provider.id)) continue;
		providers.set(provider.id, provider);
	}
}
const rows = [...providers.values()].sort((a, b) => a.id.localeCompare(b.id)).map((p) =>
	`\t{ID: ${JSON.stringify(p.id)}, Name: ${JSON.stringify(p.name)}, OAuth: ${Boolean(p.auth.oauth)}, Subscription: ${p.auth.oauth?.isSubscription === true}, APIKey: ${Boolean(p.auth.apiKey)}},`);
writeFileSync("internal/inference/login_providers_gen.go", `// Code generated by scripts/golden-login-providers.mjs from Pi's providers; DO NOT EDIT.

package inference

// piLoginProviders are Pi's built-in providers and their sign-in methods.
var piLoginProviders = []piLoginProvider{
${rows.join("\n")}
}
`);
